// 自动生成的请求头预览：复刻 Go 侧运行时行为（Host/CT/CL/Accept-Encoding/UA 兜底）
import { describe, it, expect, beforeEach } from 'vitest'
import { autoGeneratedHeaders, queryEscapeGo } from '../src/lib/headers-preview'
import { newRequest } from '../src/types/models'
import { workspace } from '../src/stores/workspace'

function keys(hs: { key: string }[]): string[] {
  return hs.map((h) => h.key)
}

beforeEach(() => {
  workspace.projects = []
  workspace.currentProjectId = null
})

describe('autoGeneratedHeaders', () => {
  it('GET 无 body：Host + Accept-Encoding；UA 已由默认头设置 → 不再出现', () => {
    const r = newRequest({ url: 'https://api.example.com:8443/x' })
    const hs = autoGeneratedHeaders(r)
    expect(hs).toEqual([
      { key: 'Host', value: 'api.example.com:8443' },
      { key: 'Accept-Encoding', value: 'gzip' },
    ])
  })

  it('raw json body：CT application/json + Content-Length 为 UTF-8 字节长', () => {
    const r = newRequest({ url: 'https://a.com', body: { type: 'raw', raw: '{"中文":1}', rawLang: 'json' } })
    const hs = autoGeneratedHeaders(r)
    expect(keys(hs)).toEqual(['Host', 'Content-Type', 'Content-Length', 'Accept-Encoding'])
    expect(hs.find((h) => h.key === 'Content-Type')?.value).toBe('application/json')
    expect(hs.find((h) => h.key === 'Content-Length')?.value).toBe(String(new TextEncoder().encode('{"中文":1}').length))
  })

  it('urlencoded：CT + Content-Length 与 Go url.Values.Encode() 一致（空格→+）', () => {
    const r = newRequest({
      url: 'https://a.com',
      body: { type: 'urlencoded', urlencoded: [{ key: 'a b', value: 'x y', enabled: true }] },
    })
    const hs = autoGeneratedHeaders(r)
    expect(hs.find((h) => h.key === 'Content-Type')?.value).toBe('application/x-www-form-urlencoded')
    expect(hs.find((h) => h.key === 'Content-Length')?.value).toBe(String('a+b=x+y'.length))
  })

  it('form-data：CT multipart/form-data 但不出 Content-Length（boundary 运行时生成）', () => {
    const r = newRequest({
      url: 'https://a.com',
      body: { type: 'form-data', formData: [{ key: 'f', value: '', enabled: true, type: 'file', filePath: '/tmp/f' }] },
    })
    const hs = autoGeneratedHeaders(r)
    expect(hs.find((h) => h.key === 'Content-Type')?.value).toBe('multipart/form-data')
    expect(hs.find((h) => h.key === 'Content-Length')).toBeUndefined()
  })

  it('用户删掉 UA 行 → 预览出现 Go 兜底 Voltra/0.2.0；用户自设 Accept-Encoding → 不出', () => {
    const r = newRequest({ url: 'https://a.com' })
    r.headers = r.headers.filter((h) => h.key !== 'User-Agent')
    r.headers.push({ key: 'Accept-Encoding', value: 'br', enabled: true })
    const hs = autoGeneratedHeaders(r)
    expect(hs.find((h) => h.key === 'User-Agent')?.value).toBe('Voltra/0.2.0')
    expect(hs.find((h) => h.key === 'Accept-Encoding')).toBeUndefined()
  })

  it('空 URL 不出 Host；无 scheme 地址可解析 Host', () => {
    expect(keys(autoGeneratedHeaders(newRequest({ url: '' })))).not.toContain('Host')
    const r = newRequest({ url: 'api.example.com/x' })
    expect(autoGeneratedHeaders(r).find((h) => h.key === 'Host')?.value).toBe('api.example.com')
  })
})

describe('queryEscapeGo（与 Go url.QueryEscape 逐字符一致）', () => {
  it('unreserved 不转义、空格→+、其余 %XX 大写', () => {
    expect(queryEscapeGo('A-Za-z0-9-_.~')).toBe('A-Za-z0-9-_.~')
    expect(queryEscapeGo('a b')).toBe('a+b')
    expect(queryEscapeGo('!\'()*')).toBe('%21%27%28%29%2A')
    expect(queryEscapeGo('/?&=')).toBe('%2F%3F%26%3D')
  })
  it('非 ASCII 走 UTF-8 字节', () => {
    expect(queryEscapeGo('中')).toBe('%E4%B8%AD')
  })
})
